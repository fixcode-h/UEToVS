using System;
using System.IO;
using System.Linq;
using UEToVS.Contracts;
using UEToVS.Engine.Navigation;
using Xunit;

namespace UEToVS.Engine.Tests
{
    public class UbtDefinitionLocatorTests : IDisposable
    {
        private readonly string _root = Path.Combine(Path.GetTempPath(), "uetovs-ubtdefs-" + Guid.NewGuid().ToString("N"));

        public void Dispose()
        {
            try { Directory.Delete(_root, true); } catch (IOException) { }
        }

        private string MakeProject()
        {
            string module = Path.Combine(_root, "Source", "MyGame");
            Directory.CreateDirectory(Path.Combine(module, "Private"));
            File.WriteAllText(Path.Combine(_root, "MyGame.uproject"), "{}");
            File.WriteAllText(Path.Combine(module, "MyGame.Build.cs"), "");
            string source = Path.Combine(module, "Private", "Foo.cpp");
            File.WriteAllText(source, "#if WITH_EDITOR\n#endif\n");
            Directory.CreateDirectory(Path.Combine(_root, "Intermediate", "Build"));
            return source;
        }

        [Fact]
        public void FindsTheDefineInTheNewestDefinitionsHeader()
        {
            string source = MakeProject();
            Assert.Null(UbtDefinitionLocator.Find(source, "WITH_EDITOR")); // 还没编译

            // UE 5.3+：Win64/x64/<Target>/<Config>/<Module>/Definitions.<Module>.h
            string dev = Path.Combine(_root, "Intermediate", "Build", "Win64", "x64", "MyGameEditor", "Development", "MyGame");
            Directory.CreateDirectory(dev);
            string devFile = Path.Combine(dev, "Definitions.MyGame.h");
            File.WriteAllText(devFile, "// Generated by UnrealBuildTool\n#pragma once\n#define UE_IS_ENGINE_MODULE 0\n#define WITH_EDITORONLY_DATA 1\n#define WITH_EDITOR 1\n#define MYGAME_API DLLEXPORT\n");
            File.SetLastWriteTimeUtc(devFile, DateTime.UtcNow.AddHours(-1));
            // 另一个配置更新一些：优先
            string dbg = Path.Combine(_root, "Intermediate", "Build", "Win64", "x64", "MyGameEditor", "DebugGame", "MyGame");
            Directory.CreateDirectory(dbg);
            string dbgFile = Path.Combine(dbg, "Definitions.MyGame.h");
            File.WriteAllText(dbgFile, "#pragma once\n#define WITH_EDITOR 1\n");

            var s = UbtDefinitionLocator.Find(source, "WITH_EDITOR");
            Assert.NotNull(s);
            Assert.Equal(dbgFile, s.Location.FilePath);
            Assert.Equal(1, s.Location.Line);
            Assert.Equal(SymbolKind.Macro, s.Kind);
            Assert.Equal("#define WITH_EDITOR 1", s.Signature);

            var api = UbtDefinitionLocator.Find(source, "MYGAME_API");
            Assert.Equal(devFile, api.Location.FilePath);
            Assert.Equal(5, api.Location.Line);
            Assert.Null(UbtDefinitionLocator.Find(source, "WITH_EDITORONLY")); // 前缀不算
        }

        [Fact]
        public void FindsTheOlderLayoutWithoutArchitecture()
        {
            string source = MakeProject();
            // UE 5.0–5.2：Win64/<Target>/<Config>/<Module>
            string dev = Path.Combine(_root, "Intermediate", "Build", "Win64", "UnrealEditor", "Development", "MyGame");
            Directory.CreateDirectory(dev);
            File.WriteAllText(Path.Combine(dev, "Definitions.MyGame.h"), "#define WITH_EDITOR 1\n");
            Assert.Single(UbtDefinitionLocator.DefinitionFiles(Path.Combine(_root, "Intermediate", "Build"), "MyGame"));
            Assert.Equal(0, UbtDefinitionLocator.Find(source, "WITH_EDITOR").Location.Line);
        }

        [Fact]
        public void KnownUbtMacros()
        {
            Assert.True(UbtDefinitionLocator.IsKnownUbtMacro("WITH_EDITOR"));
            Assert.True(UbtDefinitionLocator.IsKnownUbtMacro("UE_BUILD_SHIPPING"));
            Assert.True(UbtDefinitionLocator.IsKnownUbtMacro("MYGAME_API"));
            Assert.False(UbtDefinitionLocator.IsKnownUbtMacro("MyGame_API"));
            Assert.False(UbtDefinitionLocator.IsKnownUbtMacro("FOO"));
        }

        [Theory]
        [InlineData("#if WITH_EDITOR", 6, "WITH_EDITOR", true)]
        [InlineData("#  ifdef  WITH_EDITORONLY_DATA", 12, "WITH_EDITORONLY_DATA", true)]
        [InlineData("#if defined(A) && B", 18, "B", false)]
        [InlineData("#define X(a) Y(a) /* Z */", 13, "Y", false)]
        [InlineData("#define X 1", 8, "X", true)]
        public void DirectiveIdentifierAt(string line, int offset, string expected, bool first)
        {
            var bytes = System.Text.Encoding.UTF8.GetBytes(line);
            Assert.True(SymbolResolver.DirectiveIdentifierAt(bytes, 0, bytes.Length, offset, out int start, out int length, out bool f));
            Assert.Equal(expected, line.Substring(start, length));
            Assert.Equal(first, f);
        }

        [Theory]
        [InlineData("#if WITH_EDITOR // X", 19)]
        [InlineData("#define X /* Y */ 1", 13)]
        [InlineData("#if 0x1F", 6)]
        [InlineData("#if A", 2)]
        public void DirectiveIdentifierAt_NotAnIdentifier(string line, int offset)
        {
            var bytes = System.Text.Encoding.UTF8.GetBytes(line);
            Assert.False(SymbolResolver.DirectiveIdentifierAt(bytes, 0, bytes.Length, offset, out _, out _, out _));
        }
    }
}
