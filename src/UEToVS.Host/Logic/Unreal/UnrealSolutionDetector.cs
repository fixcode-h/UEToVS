using System;
using System.IO;
using System.Linq;

namespace UEToVS.Host.Logic.Unreal
{
    public enum UnrealSolutionKind
    {
        /// <summary>Not an Unreal Engine solution: UEToVS stays idle (no engine, no IntelliSense takeover).</summary>
        None = 0,

        /// <summary>A game/program project: a .uproject was found.</summary>
        Project = 1,

        /// <summary>An engine solution (UE5.sln) without a game project next to it.</summary>
        Engine = 2,
    }

    /// <summary>Result of <see cref="UnrealSolutionDetector.Detect"/>. <see cref="Reason"/> is a stable id for logs.</summary>
    public sealed class UnrealSolutionInfo
    {
        public static readonly UnrealSolutionInfo NotUnreal = new UnrealSolutionInfo(UnrealSolutionKind.None, null, null, "none");

        public UnrealSolutionInfo(UnrealSolutionKind kind, string projectFile, string engineRoot, string reason)
        {
            Kind = kind;
            ProjectFile = projectFile;
            EngineRoot = engineRoot;
            Reason = reason;
        }

        public UnrealSolutionKind Kind { get; }
        public bool IsUnreal => Kind != UnrealSolutionKind.None;

        /// <summary>Full path of the .uproject (null for engine solutions).</summary>
        public string ProjectFile { get; }

        /// <summary>Engine root when it is evident from the layout (engine solutions), otherwise null (the engine resolves it).</summary>
        public string EngineRoot { get; }

        /// <summary>uproject.sibling / uproject.parent / uproject.child / ubt.sln / engine.layout / none.</summary>
        public string Reason { get; }

        public override string ToString() => $"{Kind} ({Reason}) {ProjectFile ?? EngineRoot}";
    }

    /// <summary>
    /// Decides whether a solution is an Unreal Engine solution (§7.1): a .uproject in the solution directory or one of its
    /// parents, or a .sln generated by UnrealBuildTool. Pure file-system logic, no VS types; never throws.
    /// </summary>
    public static class UnrealSolutionDetector
    {
        /// <summary>How many parent directories are searched for a .uproject.</summary>
        public const int MaxParentLevels = 3;

        /// <summary>Only the head of the .sln is scanned for UBT markers.</summary>
        public const int MaxSolutionBytesScanned = 256 * 1024;

        /// <param name="solutionFile">Full path of the .sln (may be null when only the directory is known).</param>
        /// <param name="solutionDir">Directory of the solution; derived from <paramref name="solutionFile"/> when null.</param>
        public static UnrealSolutionInfo Detect(string solutionFile, string solutionDir = null)
        {
            try
            {
                if (string.IsNullOrEmpty(solutionDir) && !string.IsNullOrEmpty(solutionFile))
                    solutionDir = Path.GetDirectoryName(solutionFile);
                if (string.IsNullOrEmpty(solutionDir) || !Directory.Exists(solutionDir)) return UnrealSolutionInfo.NotUnreal;
                solutionDir = Path.GetFullPath(solutionDir);

                // 1. .uproject next to the .sln (the layout UBT generates for game projects).
                string sibling = FirstUProject(solutionDir);
                if (sibling != null) return new UnrealSolutionInfo(UnrealSolutionKind.Project, sibling, null, "uproject.sibling");

                // 2. .uproject in a parent (sln kept in a sub-folder such as <Project>/Intermediate/ProjectFiles).
                var dir = Directory.GetParent(solutionDir);
                for (int level = 0; level < MaxParentLevels && dir != null; level++, dir = dir.Parent)
                {
                    string p = FirstUProject(dir.FullName);
                    if (p != null) return new UnrealSolutionInfo(UnrealSolutionKind.Project, p, null, "uproject.parent");
                }

                // 3. Engine source tree: <dir>/Engine/Source + Engine/Build/Build.version.
                bool engineLayout = IsEngineRoot(solutionDir);

                // 4. Generated by UnrealBuildTool (UE5.sln / UE4.sln or a game sln that references Intermediate\ProjectFiles).
                bool ubt = !string.IsNullOrEmpty(solutionFile) && IsUbtGeneratedSolution(solutionFile);

                if (engineLayout || ubt)
                {
                    // A source-build engine sln often has exactly one game folder next to Engine/.
                    string child = SingleChildUProject(solutionDir);
                    if (child != null) return new UnrealSolutionInfo(UnrealSolutionKind.Project, child, engineLayout ? solutionDir : null, "uproject.child");
                    return new UnrealSolutionInfo(UnrealSolutionKind.Engine, null, engineLayout ? solutionDir : null, engineLayout ? "engine.layout" : "ubt.sln");
                }

                return UnrealSolutionInfo.NotUnreal;
            }
            catch (Exception)
            {
                // Unreadable directory etc.: treat as not Unreal; the caller logs the decision.
                return UnrealSolutionInfo.NotUnreal;
            }
        }

        public static bool IsEngineRoot(string dir)
        {
            try
            {
                return Directory.Exists(Path.Combine(dir, "Engine", "Source")) &&
                       File.Exists(Path.Combine(dir, "Engine", "Build", "Build.version"));
            }
            catch (Exception)
            {
                return false;
            }
        }

        /// <summary>
        /// True when the solution text carries UnrealBuildTool markers: project files under Intermediate\ProjectFiles and
        /// an engine project named UE4/UE5 (or the "Engine"/"Games" folder layout UBT emits).
        /// </summary>
        public static bool IsUbtGeneratedSolution(string solutionFile)
        {
            try
            {
                if (!File.Exists(solutionFile)) return false;
                string head = ReadHead(solutionFile, MaxSolutionBytesScanned);
                return IsUbtGeneratedSolutionText(head);
            }
            catch (Exception)
            {
                return false;
            }
        }

        public static bool IsUbtGeneratedSolutionText(string text)
        {
            if (string.IsNullOrEmpty(text)) return false;
            bool projectFiles = text.IndexOf(@"Intermediate\ProjectFiles\", StringComparison.OrdinalIgnoreCase) >= 0 ||
                                text.IndexOf("Intermediate/ProjectFiles/", StringComparison.OrdinalIgnoreCase) >= 0;
            if (!projectFiles) return false;
            bool engineProject = text.IndexOf("\"UE5\"", StringComparison.Ordinal) >= 0 ||
                                 text.IndexOf("\"UE4\"", StringComparison.Ordinal) >= 0 ||
                                 text.IndexOf("UE5.vcxproj", StringComparison.OrdinalIgnoreCase) >= 0 ||
                                 text.IndexOf("UE4.vcxproj", StringComparison.OrdinalIgnoreCase) >= 0;
            bool folders = text.IndexOf("= \"Engine\", \"Engine\"", StringComparison.Ordinal) >= 0 &&
                           text.IndexOf("= \"Games\", \"Games\"", StringComparison.Ordinal) >= 0;
            return engineProject || folders;
        }

        private static string ReadHead(string path, int maxBytes)
        {
            using (var fs = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.ReadWrite | FileShare.Delete))
            using (var reader = new StreamReader(fs))
            {
                var buffer = new char[Math.Min(maxBytes, (int)Math.Max(1, Math.Min(fs.Length, int.MaxValue)))];
                int read = reader.ReadBlock(buffer, 0, buffer.Length);
                return new string(buffer, 0, read);
            }
        }

        private static string FirstUProject(string dir)
        {
            try
            {
                return Directory.EnumerateFiles(dir, "*.uproject", SearchOption.TopDirectoryOnly)
                    .OrderBy(p => p, StringComparer.OrdinalIgnoreCase)
                    .FirstOrDefault();
            }
            catch (Exception)
            {
                return null;
            }
        }

        private static string SingleChildUProject(string dir)
        {
            string found = null;
            try
            {
                foreach (var sub in Directory.EnumerateDirectories(dir))
                {
                    string name = Path.GetFileName(sub);
                    if (string.Equals(name, "Engine", StringComparison.OrdinalIgnoreCase) || name.StartsWith(".", StringComparison.Ordinal)) continue;
                    string p = FirstUProject(sub);
                    if (p == null) continue;
                    if (found != null) return null; // ambiguous: several games next to the engine
                    found = p;
                }
            }
            catch (Exception)
            {
                return null;
            }
            return found;
        }
    }
}
