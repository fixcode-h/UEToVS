    public static class Loc
    {
        public static bool English { get; set; }

        /// <summary>Optional host lookup; return null to fall back to the built-in table.</summary>
        public static Func<string, string> Override { get; set; }

        public static string T(string key)
        {
            var o = Override?.Invoke(key);
            if (o != null) return o;
            var table = English ? En : Zh;
            if (table.TryGetValue(key, out var s)) return s;
            if (Zh.TryGetValue(key, out s)) return s;
            return key;
        }

        public static string F(string key, params object[] args)
        {
            try { return string.Format(T(key), args); }
            catch (FormatException) { return T(key); }
        }

        public static IEnumerable<string> Keys => Zh.Keys;
        internal static IReadOnlyDictionary<string, string> ZhTable => Zh;
        internal static IReadOnlyDictionary<string, string> EnTable => En;

